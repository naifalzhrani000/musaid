// تحليل نصوص عربي بقواعد ثابتة (بلا نموذج لغوي): تصنيف الشكاوى، وكشف محاولات تبادل بيانات الاتصال أو الدفع خارج المنصة.
import {normAr} from '../core.js';

const AR_DIGITS='٠١٢٣٤٥٦٧٨٩',FA_DIGITS='۰۱۲۳۴۵۶۷۸۹';
export const latinDigits=s=>String(s||'').replace(/[٠-٩]/g,d=>AR_DIGITS.indexOf(d)).replace(/[۰-۹]/g,d=>FA_DIGITS.indexOf(d));
// يخفي الأرقام الطويلة قبل تخزين أي مقتطف في نتائج الذكاء
export const maskDigits=s=>latinDigits(s).replace(/\d{4,}/g,m=>m.slice(0,2)+'•'.repeat(m.length-2)).slice(0,140);

const STRONG=['بدون عموله','خارج المنصه','تحويل مباشر','حول لي','حول علي','ادفع لي مباشر','نتفق خارج','بدون المنصه','لا تدفع عن طريق'];
const WEAK=['واتساب','واتس','رقمي','سناب','تليجرام','تلقرام'];

// يعيد درجة الاشتباه وأسبابها. hasAgreement: يوجد اتفاق قائم بين الطرفين (الجوال بعد الاتفاق مسموح، ولا يُحتسب).
export const bypassSignals=(body,hasAgreement)=>{
  const raw=latinDigits(body),compact=raw.replace(/[\s\-.]/g,''),n=normAr(raw),why=[];let score=0;
  if(/SA\d{22}/i.test(compact)){score+=2;why.push('رقم آيبان في المحادثة')}
  if(/(?:\+?9665|009665|05)\d{8}/.test(compact)&&!hasAgreement){score+=1;why.push('رقم جوال قبل وجود اتفاق')}
  if(/[\w.+-]+@[\w-]+\.[\w.]+/.test(raw)&&!hasAgreement){score+=1;why.push('بريد إلكتروني قبل وجود اتفاق')}
  for(const k of STRONG)if(n.includes(k)){score+=2;why.push('عبارة: '+k);break}
  for(const k of WEAK)if(n.includes(k)){score+=1;why.push('عبارة: '+k);break}
  return{score,why};
};

