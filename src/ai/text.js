export const classify=text=>{
  const n=' '+normAr(text)+' ';let best=null;
  for(const [key,label,pri,words] of CATS){const hits=words.filter(w=>n.includes(w)).length;if(hits&&(!best||pri>best.pri||(pri===best.pri&&hits>best.hits)))best={key,label,pri,hits}}
  return best?{cat:best.key,label:best.label,priority:best.pri}:{cat:'other',label:'عام',priority:1};
};
