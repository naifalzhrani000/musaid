(function(){
 var EN = sessionStorage.getItem('lang') === 'en';
 document.documentElement.lang = EN ? 'en' : 'ar';
 document.documentElement.dir = EN ? 'ltr' : 'rtl';
 if (!EN) return;
 var AR = '[\\u0600-\\u06FF]';
 function build(dict){
   return Object.keys(dict).sort(function(a,b){return b.length-a.length}).map(function(k){
     var esc = k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
     return [new RegExp('(^|[^\\u0600-\\u06FF])' + esc + '(?!' + AR + ')', 'g'), dict[k]];
   });
 }
 var MAIN = build(window.EN_DICT);
 var ADMIN = build(Object.assign({}, window.EN_DICT, window.EN_ADMIN || {}));
 var hasAr = /[؀-ۿ]/;
 function fix(s, list){ for (var i=0;i<list.length;i++) s = s.replace(list[i][0], function(m,p){ return p + list[i][1]; }); return s; }
 function pu(s){return s.replace(/؟/g,"?").replace(/،/g,",").replace(/؛/g,";");}
 // Admin console text uses the admin keys; everything else uses the main dictionary.
 function listFor(n){ var el = n.nodeType === 3 ? n.parentNode : n; return (el && el.closest && el.closest('.mg-shell')) ? ADMIN : MAIN; }
 function tr(n){
   if (n.nodeType === 3) { if (n.parentNode && n.parentNode.closest && n.parentNode.closest('[data-noen]')) return; if (hasAr.test(n.nodeValue)) { var o = pu(fix(n.nodeValue, listFor(n))); if (o !== n.nodeValue) n.nodeValue = o; } return; }
   if (n.nodeType === 1 && n.getAttribute) {
     var de = n.getAttribute('data-en'); if (de !== null) { if (n.getAttribute('data-en-done') !== de) { n.setAttribute('data-en-done', de); n.innerHTML = de; } return; }
     ['placeholder','aria-label','title'].forEach(function(a){ var v = n.getAttribute(a); if (v && hasAr.test(v)) { var o = pu(fix(v, listFor(n))); if (o !== v) n.setAttribute(a, o); } });
   }
 }
 function walk(root){ if (!root || !root.nodeType) return; tr(root); var w = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT); var c = w.nextNode(); while (c) { tr(c); c = w.nextNode(); } }
 walk(document.head); walk(document.body);
 new MutationObserver(function(ms){ ms.forEach(function(m){ if (m.type === 'characterData') tr(m.target); else m.addedNodes.forEach(walk); }); })
   .observe(document.documentElement, { childList: true, subtree: true, characterData: true });
 // Native confirm() text is not a DOM node, so translate it here.
 var nativeConfirm = window.confirm;
 window.confirm = function(m){ return nativeConfirm.call(window, pu(fix(String(m), ADMIN))); };
})();
